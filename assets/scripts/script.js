function upaName(d, u) {
  var r = (UPA[d] || []).filter(function (p) {
    return p[0] === u;
  })[0];
  return r ? (lang === "bn" ? r[1] : r[0]) : "";
}
function fillUpazilas() {
  var s = $("f-upa"),
    ds = $("f-dist").value,
    v = s.value,
    list = UPA[ds] || [];
  s.disabled = !list.length;
  s.innerHTML =
    '<option value="">' +
    t("all_upa") +
    "</option>" +
    list
      .map(function (x) {
        return (
          '<option value="' +
          x[0] +
          '">' +
          (lang === "bn" ? x[1] : x[0]) +
          "</option>"
        );
      })
      .join("");
  s.value = list.some(function (x) {
    return x[0] === v;
  })
    ? v
    : "";
}
function fillDivisions() {
  var s = $("f-div"),
    first = !s.options.length,
    v = s.value;
  s.innerHTML =
    DIVISIONS.map(function (x) {
      return '<option value="' + x.id + '">' + x[lang] + "</option>";
    }).join("") +
    '<option value="">' +
    t("all_div") +
    "</option>";
  s.value = first ? "dhaka" : v;
}
function fillDistricts() {
  var d = $("f-dist"),
    vs = $("f-div").value,
    v = d.value;
  var list = DISTRICTS.filter(function (x) {
    return x.div === vs;
  });
  d.disabled = !vs;
  d.innerHTML =
    '<option value="">' +
    t("all_dist") +
    "</option>" +
    list
      .map(function (x) {
        return '<option value="' + x.id + '">' + x[lang] + "</option>";
      })
      .join("");
  d.value = list.some(function (x) {
    return x.id === v;
  })
    ? v
    : "";
}
function renderDonors() {
  var dv = $("f-div").value,
    d = $("f-dist").value,
    u = $("f-upa").value,
    a = $("f-area").value.trim().toLowerCase();
  var list = DONORS.filter(function (x) {
    var gOk =
      !group || (compat ? RECEIVE[group].indexOf(x.g) > -1 : x.g === group);
    return (
      gOk &&
      (!dv || divOf(x.d) === dv) &&
      (!d || x.d === d) &&
      (!u || x.u === u) &&
      (!a ||
        x.area.toLowerCase().indexOf(a) > -1 ||
        (AREA_BN[x.area] || "").indexOf(a) > -1)
    );
  }).sort(function (p, q) {
    var di = function (id) {
      return DISTRICTS.findIndex(function (x) {
        return x.id === id;
      });
    };
    return di(p.d) - di(q.d) || (q.ago >= 120) - (p.ago >= 120);
  });
  $("count").textContent = num(list.length) + " " + t("found");
  if (!list.length) {
    $("donors").innerHTML = '<div class="empty">' + t("none") + "</div>";
    return;
  }
  $("donors").innerHTML = list
    .map(function (x) {
      var ok = x.ago >= 120,
        area = lang === "bn" ? AREA_BN[x.area] : x.area;
      return (
        '<article class="card"><div class="g">' +
        x.g +
        '</div><div><div class="name">' +
        x[lang] +
        '</div><div class="meta">' +
        [area, upaName(x.d, x.u), distName(x.d)].filter(Boolean).join(", ") +
        '</div><div class="meta">' +
        t("last") +
        " " +
        num(x.ago) +
        " " +
        t("days") +
        '</div></div><div class="foot"><span class="pill ' +
        (ok ? "ok" : "wait") +
        '">' +
        (ok ? t("avail") : t("wait")) +
        '</span><button type="button" class="btn" data-demo>' +
        t("contact") +
        "</button></div></article>"
      );
    })
    .join("");
}
